    CAST(NULL AS VARCHAR) AS source_system_identifier,
    CAST(NULL AS TIMESTAMP(6) WITH TIME ZONE) AS source_timestamp,
    CAST(NULL AS VARCHAR) AS interaction_id,
    CAST(NULL AS VARCHAR) AS support_category,
    CAST(NULL AS VARCHAR) AS agent_pseudo_name,
    CAST(NULL AS VARCHAR) AS contact_date,
    CAST(NULL AS VARCHAR) AS interaction_status,
    CAST(NULL AS VARCHAR) AS interaction_type,
    CAST(NULL AS VARCHAR) AS type_of_customer,
    CAST(NULL AS VARCHAR) AS interaction_duration,
    CAST(NULL AS VARCHAR) AS total_time,
    CAST(NULL AS VARCHAR) AS status_of_customer_incident,
    CAST(NULL AS VARCHAR) AS resolved_in_first_contact,
    CAST(NULL AS VARCHAR) AS solution_type,
    CAST(NULL AS VARCHAR) AS rating,
    CAST(NULL AS BIGINT) AS serial_number
