SELECT
    CAST(NULL AS VARCHAR) AS source_system_identifier,
    CAST(NULL AS TIMESTAMP(6) WITH TIME ZONE) AS source_timestamp,
    CAST(NULL AS VARCHAR) AS ticket_identifier,
    CAST(NULL AS VARCHAR) AS support_category,
    CAST(NULL AS VARCHAR) AS agent_name,
    CAST(NULL AS VARCHAR) AS date_of_call,
    CAST(NULL AS VARCHAR) AS call_status,
    CAST(NULL AS VARCHAR) AS call_type,
    CAST(NULL AS VARCHAR) AS type_of_customer,
    CAST(NULL AS VARCHAR) AS duration,
    CAST(NULL AS VARCHAR) AS work_time,
    CAST(NULL AS VARCHAR) AS ticket_status,
    CAST(NULL AS VARCHAR) AS resolved_in_first_contact,
    CAST(NULL AS VARCHAR) AS resolution_category,
    CAST(NULL AS VARCHAR) AS rating,
    CAST(NULL AS VARCHAR) AS source_object,
    CAST(NULL AS VARCHAR) AS source_etag,
    CAST(NULL AS BIGINT) AS source_row
WHERE
    1 = 0
