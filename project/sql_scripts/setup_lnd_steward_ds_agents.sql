SELECT
    CAST(NULL AS BIGINT) AS agent_id,
    CAST(NULL AS VARCHAR) AS first_name,
    CAST(NULL AS VARCHAR) AS middle_name,
    CAST(NULL AS VARCHAR) AS last_name,
    CAST(NULL AS VARCHAR) AS pseudo_code,
    CAST(NULL AS BIGINT) AS source_id,
    CAST(NULL AS BOOLEAN) AS is_active,
    CAST(NULL AS BIGINT) AS upload_id,
    CAST(NULL AS BOOLEAN) AS locked,
    CAST(NULL AS BIGINT) AS landing_task_id,
    CAST(NULL AS VARCHAR) AS item_key
WHERE
    1 = 0
